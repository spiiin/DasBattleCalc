"""Writes scripts/games/ffta2/ffta2_charset.das from charset.json: the
single-byte characters 0x00..0xA8 as a daslang array (control codes 0xC0..
are decoded in ffta2_text.das).

python research/ffta2/gen_charset.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'scripts', 'games', 'ffta2', 'ffta2_charset.das')
BS = chr(92)


def das_string(s):
    if s == '\r':
        return '""'
    if s.startswith(BS) and s.endswith(BS):
        s = '[' + s[1:-1] + ']'        # \squareleft\ -> [squareleft]
    out = ''
    for ch in s:
        if ch in (BS, '"', '{', '}'):
            out += BS + ch
        else:
            out += ch
    return '"' + out + '"'


def main():
    cs = {int(k): v for k, v in json.load(open(os.path.join(HERE, 'charset.json'), encoding='utf-8')).items()}
    n = 0xA9
    items = [das_string(cs.get(i, '?')) for i in range(n)]
    lines = []
    row = '    '
    for i, it in enumerate(items):
        piece = it + (', ' if i + 1 < n else '')
        if len(row) + len(piece) > 100:
            lines.append(row.rstrip())
            row = '    '
        row += piece
    lines.append(row.rstrip())
    src = ('options gen2\n'
           'options indenting = 4\n\n'
           '// FFTA2 text: the characters 0x00..0xA8 (generated by\n'
           '// research/ffta2/gen_charset.py from the charset of Rurusachi/ffta2-editor, MIT).\n'
           'module ffta2_charset shared public\n\n'
           'let FFTA2_CHARS = fixed_array<string>(\n' + '\n'.join(lines) + ')\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(src)
    print('wrote', OUT, n, 'characters')


if __name__ == '__main__':
    main()
